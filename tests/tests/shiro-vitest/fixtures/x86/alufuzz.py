#!/usr/bin/env python3
# Generates alufuzz.c (python3 alufuzz.py > alufuzz.c; x86-engine.test.ts does this in its build dir), the fixture for "every ALU form".
# ALU ops (wjit category 0) in every operand form and flag use.
ops = ['add', 'or', 'adc', 'sbb', 'and', 'sub', 'xor', 'cmp']
W = {8: ('b', 'b'), 16: ('w', 'w'), 32: ('l', 'k'), 64: ('q', 'q')}
imm8 = [-1, 1, 127, -128, 5]
imm32 = [-1, 0x7fffffff, -0x80000000, 0x12345, 200]
conds = ['e', 'b', 'l', 'le', 's', 'o', 'be', 'p']
fns = []
out = []
def fn(name, body, uses_mem):
    # r: in/out register (rdi slot), b: second register, m: memory cell
    fns.append(name)
    out.append(f'''static void {name}(u64 a, u64 b) {{
  u64 r = a, f = 0; volatile u64 m = b; (void)m;
  asm volatile({body} : "+r"(r), "+r"(f), "+m"(m) : "r"(b) : "cc");
  mix(r); mix(f); mix(m);
}}''')
for op in ops:
    for w, (sfx, mod) in W.items():
        rd = f'%{mod}0' if mod != 'q' else '%0'
        rs = f'%{mod}3' if mod != 'q' else '%3'
        mm = f'{sfx}'
        forms = [('rr', f'{op}{sfx} {rs}, {rd}'), ('rm', f'{op}{sfx} %2, {rd}'), ('mr', f'{op}{sfx} {rs}, %2')]
        for i, v in enumerate(imm8):
            if w == 8 or True:
                forms.append((f'ri8_{i}', f'{op}{sfx} ${v}, {rd}'))
                forms.append((f'mi8_{i}', f'{op}{sfx} ${v}, %2'))
        if w >= 16:
            for i, v in enumerate(imm32):
                if w == 16: v = ((v + 0x8000) & 0xffff) - 0x8000 if abs(v) > 0x7fff else v
                forms.append((f'ri32_{i}', f'{op}{sfx} ${v}, {rd}'))
        for fname, insn in forms:
            pre = '"stc\\n\\t' if op in ('adc', 'sbb') else '"'
            base = f'{op}{w}_{fname}'
            fn(base + '_dead', pre + insn + '"', True)
            fn(base + '_pushf', pre + insn + '\\n\\tpushfq\\n\\tpopq %1\\n\\tandq $0x8c5, %1"', True)
            for c in conds:
                fn(base + '_j' + c, pre + insn + f'\\n\\tj{c} 1f\\n\\tmovq $7, %1\\n\\tjmp 2f\\n1:\\tmovq $9, %1\\n2:"', True)
print('''// Generated by alufuzz.py for x86-engine.test.ts (build: gcc -static -O1 -o alufuzz alufuzz.c).
// Differential test for Blink's wasm JIT: wjit category 0 (the ALU ops add/or/adc/sbb/and/sub/xor/cmp, 00-3f and 80-83)
// in every width and operand form (reg, reg<-mem, mem<-reg, imm8, imm32, mem<-imm), with the flags dead, pushed, and
// consumed by a fused jcc. One checksum line per variant; the JIT and BLINK_WJIT=0 must print the same lines.
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
typedef uint64_t u64;
static u64 s = 88172645463325252ull;
static u64 rnd(void) { s ^= s << 13; s ^= s >> 7; s ^= s << 17; return s; }
static u64 pick(void) {
  static const u64 edge[] = {0, 1, 2, 0x7f, 0x80, 0xff, 0x7fff, 0x8000, 0xffff, 0x7fffffff, 0x80000000, 0xffffffff,
                             0x100000000, 0x7fffffffffffffff, 0x8000000000000000, -1ull, -2ull};
  u64 r = rnd();
  if ((r & 3) == 0) return edge[(r >> 2) % (sizeof(edge) / sizeof(edge[0]))];
  if ((r & 3) == 1) return rnd() & 0xff;
  return rnd();
}
static u64 h;
static void mix(u64 x) { h ^= x; h *= 0x100000001b3ull; h ^= h >> 29; }
''')
print('\n'.join(out))
print('typedef void (*F)(u64, u64);')
print('static const struct { const char *name; F f; } T[] = {' + ', '.join(f'{{"{n}", {n}}}' for n in fns) + '};')
print('''int main(int argc, char **argv) {
  int n = argc > 1 ? atoi(argv[1]) : 1000;
  for (unsigned t = 0; t < sizeof(T) / sizeof(T[0]); t++) {
    h = 0; s = 88172645463325252ull + t;
    for (int i = 0; i < n; i++) T[t].f(pick(), pick());
    printf("%-24s %016llx\\n", T[t].name, (unsigned long long)h);
  }
  return 0;
}''')
